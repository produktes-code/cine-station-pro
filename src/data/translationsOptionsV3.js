// Generic Option translation helper
export const translateOptionV3 = (val, lang) => {
  if (!val) return val;
  
  // 1. Exact match in options table
  const langOptions = translationsOptionsV3[lang];
  if (langOptions && langOptions[val]) {
    return langOptions[val];
  }

  // 2. Partial term translation helper (handling parentheses e.g. "IMAX 15/70mm Film" -> "IMAX (15/70mm Film)")
  const openParen = val.indexOf("(");
  const closeParen = val.indexOf(")");
  if (openParen !== -1 && closeParen !== -1 && closeParen > openParen) {
    const prefix = val.substring(0, openParen).trim();
    const parenText = val.substring(openParen + 1, closeParen).trim();
    
    // Look up translated text for parenText
    const langTerms = translationsTermsV3[lang];
    if (langTerms && langTerms[parenText]) {
      return `${prefix} (${langTerms[parenText]})`;
    }
  }

  return val;
};
